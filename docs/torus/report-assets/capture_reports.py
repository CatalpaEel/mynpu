"""Display unedited report excerpts in a real xterm and capture its X11 window.

Requires Pillow, xterm, xwininfo and a private X display (default :97).
No synthesized tool UI or fabricated log contents are used.
"""
import os, re, subprocess, time, json, hashlib
from pathlib import Path
from PIL import ImageGrab

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RUNS = ROOT.parent / 'eda-runs'
TMP = ROOT / 'build/torus/report-capture'
TMP.mkdir(parents=True, exist_ok=True)
env = dict(os.environ, DISPLAY=os.environ.get('DISPLAY', ':97'))
old=RUNS/'20261029-torus-v3-target20k'
mid=RUNS/'20261029-torus-area-cache32-baseline'
new=RUNS/'20261029-torus-area-v4'
evidence={}

def excerpt(path,pattern=None,start=None,end=None):
    lines=path.read_text().splitlines()
    selected=[(i+1,l) for i,l in enumerate(lines) if (pattern and re.search(pattern,l)) or (not pattern and (start or 1)<=i+1<=(end or len(lines)))]
    evidence.setdefault(str(path),{'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'lines':[]})['lines'].extend(i for i,_ in selected)
    return '\n'.join(l for _,l in selected)

def snap(name,parts,cols=155):
    content='\n\n'.join(title+'\n'+text for title,text in parts)+'\n'
    f=TMP/(name+'.txt');f.write_text(content)
    # Full original lines are displayed, including wrapping in the terminal.
    rows=min(53,max(16,sum(max(1,(len(l)+cols-1)//cols) for l in content.splitlines())+2))
    p=subprocess.Popen(['xterm','-title',name,'-geometry',f'{cols}x{rows}+0+0','-fa','DejaVu Sans Mono','-fs','11','-bg','#0f1928','-fg','#e6edf5','-hold','-e','/bin/cat',str(f)],env=env)
    try:
        time.sleep(1.5)
        info=subprocess.check_output(['xwininfo','-name',name],env=env,text=True)
        def n(key):return int(re.search(key+r':\s*(-?\d+)',info).group(1))
        x,y,w,h=n('Absolute upper-left X'),n('Absolute upper-left Y'),n('Width'),n('Height')
        ImageGrab.grab(xdisplay=env['DISPLAY']).crop((x,y,x+w,y+h)).save(HERE/(name+'.png'))
    finally:p.terminate();p.wait()

snap('synth-comparison',[(str(p.name)+'/mynpu/chip_synth/area.rpt',excerpt(p/'mynpu/chip_synth/area.rpt',r'Generated by:|Generated on:|Instance .*Module|^mynpu_asic_top|      i_stream |      i_array ')) for p in [old,mid,new]])
snap('synth-timing',[(new.name+'/mynpu/chip_synth/qor.rpt  [lines 1-45]',excerpt(new/'mynpu/chip_synth/qor.rpt',start=1,end=45))],85)
snap('placement-failure',[(p.name+'/mynpu/pnr/03_launcher.log',excerpt(p/'mynpu/pnr/03_launcher.log',r'Density for the design|stdcell_area |\*\*ERROR.*IMPSP-190')) for p in [old,new]])
snap('floorplan-capacity',[(new.name+'/mynpu/pnr/reports/floorplan_check.rpt',excerpt(new/'mynpu/pnr/reports/floorplan_check.rpt',r'Generated by:|Generated on:|Design:|^WARNING|^INFO|Reporting Utilizations|Core Utilization'))])
(HERE/'screenshot-sources.json').write_text(json.dumps(evidence,indent=2)+'\n')
