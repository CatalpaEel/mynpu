from pathlib import Path
from rv32_asm import *

ROOT = Path(__file__).resolve().parent
reset()
label("_start")
li(6, 0x40000000)
li(7, 0x80001000)
for off, values in [(0, [1, -2, 3, 4, 5, -6]), (0x100, [7, 8, -9, 10, 11, -12])]:
    for i, val in enumerate(values):
        li(5, val)
        sw(5, 7, off + 4 * i)
for off, val in [
    (0x108, 0x80001000),
    (0x10C, 0x80001100),
    (0x110, 0x80001200),
    (0x114, 2),
    (0x118, 2),
    (0x11C, 3),
    (0x100, 1),
]:
    write_mmio(off, val)
poll(0x104, "mat_poll")
check(0x200, [58, -48, -83, 154])
for off, val in [(0x208, 0x80001200), (0x20C, 0x80001300), (0x210, 4), (0x214, 0), (0x200, 1)]:
    write_mmio(off, val)
poll(0x204, "relu_poll")
check(0x300, [58, 0, 0, 154])
for off, val in [
    (0x208, 0x80001200),
    (0x218, 0x80001300),
    (0x20C, 0x80001400),
    (0x214, 1),
    (0x200, 1),
]:
    write_mmio(off, val)
poll(0x204, "add_poll")
check(0x400, [116, -48, -83, 308])
# CPU also exercises 2D SRAM-copy DMA (8 bytes per row, two rows).
for off, val in [
    (0x508, 0x80001400),
    (0x50C, 0x80001500),
    (0x510, 8),
    (0x514, 2),
    (0x518, 8),
    (0x51C, 16),
    (0x520, 2),
    (0x500, 1),
]:
    write_mmio(off, val)
poll(0x504, "dma_poll")
check(0x500, [116, -48])
check(0x510, [-83, 308])
li(5, 0x600D0001)
sw(5, 6, 4)
jump("halt")
label("fail")
li(5, 0xBAD00001)
sw(5, 6, 4)
label("halt")
jump("halt")
for i, word in enumerate(code):
    if isinstance(word, int):
        continue
    pc = 0x80 + 4 * i
    if word[0] == "bne":
        _, rs1, rs2, target = word
        off = labels[target] - pc
        assert -4096 <= off <= 4094 and off % 2 == 0
        code[i] = (
            ((off >> 12 & 1) << 31)
            | ((off >> 5 & 63) << 25)
            | (rs2 << 20)
            | (rs1 << 15)
            | (1 << 12)
            | ((off >> 1 & 15) << 8)
            | ((off >> 11 & 1) << 7)
            | 0x63
        )
    else:
        off = labels[word[1]] - pc
        assert -(1 << 20) <= off < (1 << 20) and off % 2 == 0
        code[i] = (
            ((off >> 20 & 1) << 31)
            | ((off >> 1 & 1023) << 21)
            | ((off >> 11 & 1) << 20)
            | ((off >> 12 & 255) << 12)
            | 0x6F
        )
assert len(code) <= 480
image = [0x0000006F] * 32 + code
image += [0x0000006F] * (512 - len(image))
(ROOT / "boot.hex").write_text("".join(f"{w:08x}\n" for w in image))
(ROOT / "boot.S").write_text(
    "# Generated by gen_boot.py; load at SRAM 0x80000000; entry 0x80000080. RV32I, no stack or runtime.\n.option norvc\n.text\n.globl _start\n"
    + "\n".join(listing)
    + "\n"
)
print(f"Generated 2KB SRAM boot image, {len(code)} instructions; entry=0x80000080")
