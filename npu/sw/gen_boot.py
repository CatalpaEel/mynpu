#!/usr/bin/env python3
"""Dependency-free assembler for a small, real RV32I MMIO self-test."""
from pathlib import Path
ROOT = Path(__file__).resolve().parent
code=[]; labels={}; listing=[]
def emit(word,text):
    code.append(word & 0xffffffff); listing.append('    '+text)
def label(name):
    labels[name]=0x80+4*len(code); listing.append(name+':')
def lui(rd,upper):emit(((upper & 0xfffff)<<12)|(rd<<7)|0x37,f'lui x{rd}, 0x{upper & 0xfffff:x}')
def addi(rd,rs,imm):emit(((imm & 0xfff)<<20)|(rs<<15)|(rd<<7)|0x13,f'addi x{rd}, x{rs}, {imm}')
def li(rd,value):
    value &= 0xffffffff
    low=value & 0xfff
    if low & 0x800:low-=4096
    upper=((value-low)>>12)&0xfffff
    if upper:lui(rd,upper);addi(rd,rd,low)
    else:addi(rd,0,low)
def sw(rs,base,off):
    emit(((off>>5 & 0x7f)<<25)|(rs<<20)|(base<<15)|(2<<12)|((off & 31)<<7)|0x23,f'sw x{rs}, {off}(x{base})')
def lw(rd,base,off):emit(((off & 0xfff)<<20)|(base<<15)|(2<<12)|(rd<<7)|3,f'lw x{rd}, {off}(x{base})')
def andi(rd,rs,imm):emit(((imm & 0xfff)<<20)|(rs<<15)|(7<<12)|(rd<<7)|0x13,f'andi x{rd}, x{rs}, {imm}')
def branch(rs1,rs2,target):
    code.append(('bne',rs1,rs2,target));listing.append(f'    bne x{rs1}, x{rs2}, {target}')
def jump(target):code.append(('jal',target));listing.append(f'    jal x0, {target}')
def write_mmio(off,val):li(5,val);sw(5,6,off)
def poll(off,name):
    li(9,8192);label(name)
    lw(8,6,off);andi(10,8,4);branch(10,0,'fail')
    andi(10,8,2);branch(10,0,name+'_done')
    addi(9,9,-1);branch(9,0,name);jump('fail');label(name+'_done')
def check(off,values):
    for i,val in enumerate(values):lw(8,7,off+4*i);li(11,val);branch(8,11,'fail')
label('_start');li(6,0x40000000);li(7,0x80001000)
for off,values in [(0,[1,-2,3,4,5,-6]),(0x100,[7,8,-9,10,11,-12])]:
    for i,val in enumerate(values):li(5,val);sw(5,7,off+4*i)
for off,val in [(0x108,0x80001000),(0x10c,0x80001100),(0x110,0x80001200),(0x114,2),(0x118,2),(0x11c,3),(0x100,1)]:write_mmio(off,val)
poll(0x104,'mat_poll');check(0x200,[58,-48,-83,154])
for off,val in [(0x208,0x80001200),(0x20c,0x80001300),(0x210,4),(0x214,0),(0x200,1)]:write_mmio(off,val)
poll(0x204,'relu_poll');check(0x300,[58,0,0,154])
for off,val in [(0x208,0x80001200),(0x218,0x80001300),(0x20c,0x80001400),(0x214,1),(0x200,1)]:write_mmio(off,val)
poll(0x204,'add_poll');check(0x400,[116,-48,-83,308])
# CPU also exercises 2D SRAM-copy DMA (8 bytes per row, two rows).
for off,val in [(0x508,0x80001400),(0x50c,0x80001500),(0x510,8),(0x514,2),(0x518,8),(0x51c,16),(0x520,2),(0x500,1)]:write_mmio(off,val)
poll(0x504,'dma_poll');check(0x500,[116,-48]);check(0x510,[-83,308])
li(5,0x600d0001);sw(5,6,4);jump('halt')
label('fail');li(5,0xbad00001);sw(5,6,4)
label('halt');jump('halt')
for i,word in enumerate(code):
    if isinstance(word,int):continue
    pc=0x80+4*i
    if word[0]=='bne':
        _,rs1,rs2,target=word;off=labels[target]-pc
        assert -4096<=off<=4094 and off%2==0
        code[i]=((off>>12 & 1)<<31)|((off>>5 & 63)<<25)|(rs2<<20)|(rs1<<15)|(1<<12)|((off>>1 & 15)<<8)|((off>>11 & 1)<<7)|0x63
    else:
        off=labels[word[1]]-pc
        assert -(1<<20)<=off<(1<<20) and off%2==0
        code[i]=((off>>20 & 1)<<31)|((off>>1 & 1023)<<21)|((off>>11 & 1)<<20)|((off>>12 & 255)<<12)|0x6f
assert len(code)<=480
image=[0x0000006f]*32+code
image += [0x0000006f]*(512-len(image))
(ROOT/'boot.hex').write_text(''.join(f'{w:08x}\n' for w in image))
(ROOT/'boot.S').write_text('# Generated by gen_boot.py; load at SRAM 0x80000000; entry 0x80000080. RV32I, no stack or runtime.\n.option norvc\n.text\n.globl _start\n'+ '\n'.join(listing)+'\n')
print(f'Generated 2KB SRAM boot image, {len(code)} instructions; entry=0x80000080')
